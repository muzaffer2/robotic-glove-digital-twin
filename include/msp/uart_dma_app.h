/*
 * UART handle generated by CubeMX.
 */
extern UART_HandleTypeDef huart1;

/*
 * Change these definitions when another UART peripheral is used.
 */
#define UART_APP_HANDLE       huart1
#define UART_APP_INSTANCE     USART1

typedef struct
{
    char data[UART_COMMAND_MAX_LENGTH];
} UART_CommandSlot_t;

typedef struct
{
    uint8_t data[UART_TX_PACKET_MAX_LENGTH];
    uint16_t length;
} UART_TxPacket_t;

/*
 * Receive-to-Idle DMA buffer.
 */
static uint8_t uart_rx_dma_buffer[UART_RX_DMA_BUFFER_SIZE];

/*
 * This buffer joins fragmented DMA blocks until a complete line
 * ending with '\n' is received.
 */
static char uart_rx_line_buffer[UART_RX_LINE_BUFFER_SIZE];
static uint16_t uart_rx_line_index;

/*
 * Complete command queue.
 *
 * The RX callback produces commands and the main loop consumes them.
 */
static UART_CommandSlot_t uart_command_queue[UART_COMMAND_QUEUE_LENGTH];

static volatile uint16_t uart_command_head;
static volatile uint16_t uart_command_tail;

/*
 * Asynchronous TX packet queue.
 *
 * The application produces packets and UART DMA consumes them.
 */
static UART_TxPacket_t uart_tx_queue[UART_TX_QUEUE_LENGTH];

static volatile uint16_t uart_tx_head;
static volatile uint16_t uart_tx_tail;
static volatile bool uart_tx_dma_busy;

/*
 * Diagnostic counters.
 */
static volatile UART_AppStatistics_t uart_statistics;

/*
 * Internal function declarations.
 */
static void UART_AppResetState(void);

static void UART_AppProcessReceivedData(
    const uint8_t *data,
    uint16_t length
);

static void UART_AppProcessReceivedByte(
    uint8_t byte
);

static bool UART_AppPushCommand(
    const char *command
);

static void UART_AppStartNextTransmission(void);

static uint16_t UART_AppNextIndex(
    uint16_t current,
    uint16_t queue_length
);

static uint32_t UART_AppEnterCritical(void);

static void UART_AppExitCritical(
    uint32_t primask
);

UART_AppStatus_t UART_AppInit(void)
{
    UART_AppResetState();

    return UART_AppStartReception();
}

UART_AppStatus_t UART_AppStartReception(void)
{
    HAL_StatusTypeDef hal_status;

    hal_status = HAL_UARTEx_ReceiveToIdle_DMA(
        &UART_APP_HANDLE,
        uart_rx_dma_buffer,
        UART_RX_DMA_BUFFER_SIZE
    );

    if (hal_status != HAL_OK)
    {
        uart_statistics.uart_error_count++;
        return UART_APP_ERROR;
    }

    /*
     * Half-transfer events are not required for line-based commands.
     * IDLE and transfer-complete events remain enabled.
     */
    if (UART_APP_HANDLE.hdmarx != NULL)
    {
        __HAL_DMA_DISABLE_IT(
            UART_APP_HANDLE.hdmarx,
            DMA_IT_HT
        );
    }

    return UART_APP_OK;
}

UART_AppStatus_t UART_AppSendAsync(
    const uint8_t *data,
    uint16_t length)
{
    uint16_t next_head;
    uint32_t primask;

    if ((data == NULL) || (length == 0U))
    {
        return UART_APP_INVALID_ARGUMENT;
    }

    if (length > UART_TX_PACKET_MAX_LENGTH)
    {
        return UART_APP_DATA_TOO_LONG;
    }

    /*
     * Protect the queue slot while the packet is copied and published.
     *
     * This also makes the function safe when it is called from more
     * than one execution context.
     */
    primask = UART_AppEnterCritical();

    next_head = UART_AppNextIndex(
        uart_tx_head,
        UART_TX_QUEUE_LENGTH
    );

    if (next_head == uart_tx_tail)
    {
        uart_statistics.tx_drop_count++;

        UART_AppExitCritical(primask);

        return UART_APP_QUEUE_FULL;
    }

    memcpy(
        uart_tx_queue[uart_tx_head].data,
        data,
        length
    );

    uart_tx_queue[uart_tx_head].length = length;

    uart_tx_head = next_head;

    uart_statistics.tx_packet_count++;

    UART_AppExitCritical(primask);

    /*
     * Start DMA immediately if it is currently idle.
     */
    UART_AppStartNextTransmission();

    return UART_APP_OK;
}

UART_AppStatus_t UART_AppSendStringAsync(
    const char *text)
{
    size_t length;

    if (text == NULL)
    {
        return UART_APP_INVALID_ARGUMENT;
    }

    length = strlen(text);

    if (length == 0U)
    {
        return UART_APP_INVALID_ARGUMENT;
    }

    if (length > UART_TX_PACKET_MAX_LENGTH)
    {
        return UART_APP_DATA_TOO_LONG;
    }

    return UART_AppSendAsync(
        (const uint8_t *)text,
        (uint16_t)length
    );
}

UART_AppStatus_t UART_AppPrintf(
    const char *format,
    ...)
{
    char formatted_message[UART_TX_PACKET_MAX_LENGTH];
    va_list arguments;
    int formatted_length;

    if (format == NULL)
    {
        return UART_APP_INVALID_ARGUMENT;
    }

    va_start(arguments, format);

    formatted_length = vsnprintf(
        formatted_message,
        sizeof(formatted_message),
        format,
        arguments
    );

    va_end(arguments);

    if (formatted_length < 0)
    {
        return UART_APP_ERROR;
    }

    /*
     * vsnprintf returns the number of characters that would have
     * been written, excluding the null terminator.
     */
    if ((uint32_t)formatted_length >= sizeof(formatted_message))
    {
        return UART_APP_DATA_TOO_LONG;
    }

    return UART_AppSendAsync(
        (const uint8_t *)formatted_message,
        (uint16_t)formatted_length
    );
}

bool UART_AppCommandAvailable(void)
{
    return uart_command_head != uart_command_tail;
}

bool UART_AppGetCommand(
    char *destination,
    uint16_t destination_size)
{
    uint32_t primask;

    if ((destination == NULL) || (destination_size == 0U))
    {
        return false;
    }

    primask = UART_AppEnterCritical();

    if (uart_command_head == uart_command_tail)
    {
        UART_AppExitCritical(primask);

        return false;
    }

    strncpy(
        destination,
        uart_command_queue[uart_command_tail].data,
        destination_size - 1U
    );

    destination[destination_size - 1U] = '\0';

    uart_command_tail = UART_AppNextIndex(
        uart_command_tail,
        UART_COMMAND_QUEUE_LENGTH
    );

    UART_AppExitCritical(primask);

    return true;
}

bool UART_AppTxBusy(void)
{
    return uart_tx_dma_busy;
}

void UART_AppGetStatistics(
    UART_AppStatistics_t *statistics)
{
    uint32_t primask;

    if (statistics == NULL)
    {
        return;
    }

    primask = UART_AppEnterCritical();

    statistics->rx_event_count =
        uart_statistics.rx_event_count;

    statistics->rx_byte_count =
        uart_statistics.rx_byte_count;

    statistics->rx_line_overflow_count =
        uart_statistics.rx_line_overflow_count;

    statistics->command_drop_count =
        uart_statistics.command_drop_count;

    statistics->tx_packet_count =
        uart_statistics.tx_packet_count;

    statistics->tx_drop_count =
        uart_statistics.tx_drop_count;

    statistics->uart_error_count =
        uart_statistics.uart_error_count;

    UART_AppExitCritical(primask);
}

static void UART_AppResetState(void)
{
    uint32_t primask;

    primask = UART_AppEnterCritical();

    memset(
        uart_rx_dma_buffer,
        0,
        sizeof(uart_rx_dma_buffer)
    );

    memset(
        uart_rx_line_buffer,
        0,
        sizeof(uart_rx_line_buffer)
    );

    memset(
        uart_command_queue,
        0,
        sizeof(uart_command_queue)
    );

    memset(
        uart_tx_queue,
        0,
        sizeof(uart_tx_queue)
    );

    memset(
        (void *)&uart_statistics,
        0,
        sizeof(uart_statistics)
    );

    uart_rx_line_index = 0U;

    uart_command_head = 0U;
    uart_command_tail = 0U;

    uart_tx_head = 0U;
    uart_tx_tail = 0U;

    uart_tx_dma_busy = false;

    UART_AppExitCritical(primask);
}

static void UART_AppProcessReceivedData(
    const uint8_t *data,
    uint16_t length)
{
    uint16_t index;

    if ((data == NULL) || (length == 0U))
    {
        return;
    }

    for (index = 0U; index < length; index++)
    {
        UART_AppProcessReceivedByte(data[index]);
    }
}

static void UART_AppProcessReceivedByte(
    uint8_t byte)
{
    /*
     * Ignore carriage return so that both LF and CRLF
     * line endings are supported.
     */
    if (byte == '\r')
    {
        return;
    }

    /*
     * A line feed marks the end of a complete command.
     */
    if (byte == '\n')
    {
        if (uart_rx_line_index > 0U)
        {
            uart_rx_line_buffer[uart_rx_line_index] = '\0';

            (void)UART_AppPushCommand(
                uart_rx_line_buffer
            );

            uart_rx_line_index = 0U;
        }

        return;
    }

    /*
     * Add a regular byte to the current command line.
     */
    if (uart_rx_line_index <
        (UART_RX_LINE_BUFFER_SIZE - 1U))
    {
        uart_rx_line_buffer[uart_rx_line_index] =
            (char)byte;

        uart_rx_line_index++;
    }
    else
    {
        /*
         * Discard an oversized command.
         *
         * The next received bytes will form a new command.
         */
        uart_rx_line_index = 0U;

        uart_statistics.rx_line_overflow_count++;
    }
}

static bool UART_AppPushCommand(
    const char *command)
{
    uint16_t next_head;

    if (command == NULL)
    {
        return false;
    }

    next_head = UART_AppNextIndex(
        uart_command_head,
        UART_COMMAND_QUEUE_LENGTH
    );

    if (next_head == uart_command_tail)
    {
        /*
         * The command queue is full.
         * Drop the newest command.
         */
        uart_statistics.command_drop_count++;

        return false;
    }

    strncpy(
        uart_command_queue[uart_command_head].data,
        command,
        UART_COMMAND_MAX_LENGTH - 1U
    );

    uart_command_queue[uart_command_head]
        .data[UART_COMMAND_MAX_LENGTH - 1U] = '\0';

    /*
     * Publish the command after copying its contents.
     */
    uart_command_head = next_head;

    return true;
}

static void UART_AppStartNextTransmission(void)
{
    uint8_t *packet_data;
    uint16_t packet_length;
    uint32_t primask;
    HAL_StatusTypeDef hal_status;

    primask = UART_AppEnterCritical();

    /*
     * Do nothing if DMA is already active or the queue is empty.
     */
    if (uart_tx_dma_busy ||
        (uart_tx_head == uart_tx_tail))
    {
        UART_AppExitCritical(primask);

        return;
    }

    /*
     * Mark the DMA as busy before starting the transfer.
     *
     * This prevents another caller from starting the same packet.
     */
    uart_tx_dma_busy = true;

    packet_data =
        uart_tx_queue[uart_tx_tail].data;

    packet_length =
        uart_tx_queue[uart_tx_tail].length;

    UART_AppExitCritical(primask);

    hal_status = HAL_UART_Transmit_DMA(
        &UART_APP_HANDLE,
        packet_data,
        packet_length
    );

    if (hal_status != HAL_OK)
    {
        primask = UART_AppEnterCritical();

        uart_tx_dma_busy = false;

        uart_statistics.uart_error_count++;

        UART_AppExitCritical(primask);
    }
}

static uint16_t UART_AppNextIndex(
    uint16_t current,
    uint16_t queue_length)
{
    current++;

    if (current >= queue_length)
    {
        current = 0U;
    }

    return current;
}

static uint32_t UART_AppEnterCritical(void)
{
    uint32_t primask;

    primask = __get_PRIMASK();

    __disable_irq();

    return primask;
}

static void UART_AppExitCritical(
    uint32_t primask)
{
    /*
     * Restore the previous interrupt state instead of always
     * enabling interrupts.
     */
    if (primask == 0U)
    {
        __enable_irq();
    }
}

/*
 * HAL UART callbacks
 *
 * These callbacks override the weak callback implementations
 * provided by the STM32 HAL library.
 */

void HAL_UARTEx_RxEventCallback(
    UART_HandleTypeDef *huart,
    uint16_t size)
{
    if ((huart == NULL) ||
        (huart->Instance != UART_APP_INSTANCE))
    {
        return;
    }

    uart_statistics.rx_event_count++;

    if (size > UART_RX_DMA_BUFFER_SIZE)
    {
        uart_statistics.uart_error_count++;

        (void)UART_AppStartReception();

        return;
    }

    if (size > 0U)
    {
        uart_statistics.rx_byte_count += size;

        UART_AppProcessReceivedData(
            uart_rx_dma_buffer,
            size
        );
    }

    /*
     * RX DMA uses normal mode, so reception must be restarted
     * after every Receive-to-Idle event.
     */
    if (UART_AppStartReception() != UART_APP_OK)
    {
        uart_statistics.uart_error_count++;
    }
}

void HAL_UART_TxCpltCallback(
    UART_HandleTypeDef *huart)
{
    uint32_t primask;

    if ((huart == NULL) ||
        (huart->Instance != UART_APP_INSTANCE))
    {
        return;
    }

    primask = UART_AppEnterCritical();

    /*
     * Remove the packet that has just been transmitted.
     */
    if (uart_tx_tail != uart_tx_head)
    {
        uart_tx_tail = UART_AppNextIndex(
            uart_tx_tail,
            UART_TX_QUEUE_LENGTH
        );
    }

    uart_tx_dma_busy = false;

    UART_AppExitCritical(primask);

    /*
     * Start the next queued packet immediately.
     */
    UART_AppStartNextTransmission();
}

void HAL_UART_ErrorCallback(
    UART_HandleTypeDef *huart)
{
    if ((huart == NULL) ||
        (huart->Instance != UART_APP_INSTANCE))
    {
        return;
    }

    uart_statistics.uart_error_count++;

    /*
     * Abort only the RX operation.
     *
     * The TX packet queue remains unchanged.
     */
    (void)HAL_UART_AbortReceive(huart);

    /*
     * Clear the common UART error flags before restarting RX.
     */
    __HAL_UART_CLEAR_OREFLAG(huart);
    __HAL_UART_CLEAR_NEFLAG(huart);
    __HAL_UART_CLEAR_FEFLAG(huart);
    __HAL_UART_CLEAR_PEFLAG(huart);

    if (UART_AppStartReception() != UART_APP_OK)
    {
        uart_statistics.uart_error_count++;
    }
}







